-- 1. ENUMS
-- -----------------------------------------------------------------------------
CREATE TYPE monitor_type AS ENUM ('HTTP', 'TCP', 'DNS', 'ICMP');

-- 2. ACCOUNTS TABLE
-- Workspace accounts / projects
-- -----------------------------------------------------------------------------
CREATE TABLE accounts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    api_key VARCHAR(64) UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_accounts_slug ON accounts(slug);

-- 3. MONITORS TABLE
-- Target endpoints configured within an account workspace
-- -----------------------------------------------------------------------------
CREATE TABLE monitors (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    type monitor_type NOT NULL DEFAULT 'HTTP',
    
    -- Target destination (URL for HTTP, Host/IP for TCP/DNS/ICMP)
    target VARCHAR(2048) NOT NULL,
    
    -- Protocol-specific options (NULL when unused)
    port INT,
    http_method VARCHAR(10) DEFAULT 'GET',
    expected_status_code INT DEFAULT 200,
    headers JSONB DEFAULT '{}'::jsonb,
    body TEXT,
    dns_query_type VARCHAR(10) DEFAULT 'A',
    dns_expected_result VARCHAR(255),
    
    -- Timing & Execution Config
    interval_seconds INT NOT NULL DEFAULT 60,
    timeout_seconds INT NOT NULL DEFAULT 10,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_monitors_account_active ON monitors(account_id, is_active);

-- 4. MONITOR_CHECKS TABLE
-- High-volume time-series ping check logs generated by Tokio
-- -----------------------------------------------------------------------------
CREATE TABLE monitor_checks (
    id BIGSERIAL PRIMARY KEY,
    monitor_id UUID NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
    is_up BOOLEAN NOT NULL,
    status_code INT,
    response_time_ms INT,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_monitor_checks_monitor_time 
ON monitor_checks (monitor_id, created_at DESC);

-- 5. INCIDENTS TABLE
-- Tracks downtime events from failure onset to resolution
-- -----------------------------------------------------------------------------
CREATE TABLE incidents (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    monitor_id UUID NOT NULL REFERENCES monitors(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ,
    cause TEXT NOT NULL,
    is_resolved BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_incidents_monitor_unresolved 
ON incidents (monitor_id, is_resolved);

-- 6. APP_CONFIG TABLE
-- Global application settings (webhooks, data retention policies)
-- -----------------------------------------------------------------------------
CREATE TABLE app_config (
    key VARCHAR(50) PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);